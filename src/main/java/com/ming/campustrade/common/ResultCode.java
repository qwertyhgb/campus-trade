package com.ming.campustrade.common;

import lombok.Getter;

/**
 * 统一响应状态码枚举
 *
 * 设计目的：
 * 集中管理项目中所有的响应状态码和对应的提示信息，避免在代码中到处写魔法数字（如直接写 200、1001）。
 * 使用枚举的好处：
 * 1. 类型安全：编译器会检查，写错名字直接报错，而写错数字不会报错
 * 2. 集中维护：修改提示信息只需改这一处，不用全局搜索替换
 * 3. 语义清晰：ResultCode.USER_NOT_FOUND 比数字 1001 可读性强得多
 *
 * 错误码编号规则（分段设计，方便快速定位问题模块）：
 * - 200~599：   标准 HTTP 状态码（通用错误，如参数错误、未登录、服务器错误等）
 * - 1001~1999： 用户模块业务错误（登录、注册、权限相关）
 * - 2001~2999： 商品模块业务错误（商品查询、状态相关）
 * - 3001~3999： 分类模块业务错误（分类增删改查相关）
 * - 4001~4999： 订单模块业务错误（下单、确认、取消相关）
 * - 5001~5999： 收藏模块业务错误（收藏、取消收藏相关）
 *
 * 为什么不用 HTTP 状态码来表示业务错误？
 * 因为 HTTP 状态码数量有限且含义固定，无法表达细粒度的业务错误（如"不能购买自己的商品"）。
 * 国内项目常见做法：HTTP 状态码统一返回 200，真正的业务状态码放在 JSON body 的 code 字段中，
 * 前端根据 code 字段判断成功/失败并展示对应的提示信息。
 */
@Getter // Lombok 注解：自动生成 getCode() 和 getMessage() 方法
public enum ResultCode {

    // ==================== 通用状态码（对应标准 HTTP 状态码） ====================

    /** 请求成功 */
    SUCCESS(200, "success"),

    /** 请求参数错误（如缺少必填字段、格式不正确等） */
    BAD_REQUEST(400, "请求参数错误"),

    /** 未登录或登录已过期（前端收到此码应跳转到登录页） */
    UNAUTHORIZED(401, "未登录或登录已过期"),

    /** 无权限访问（已登录但角色/权限不足） */
    FORBIDDEN(403, "无权限访问"),

    /** 请求的资源不存在 */
    NOT_FOUND(404, "资源不存在"),

    /** 请求方法不被允许（如用 GET 访问只支持 POST 的接口） */
    METHOD_NOT_ALLOWED(405, "请求方法不被允许"),

    /** 服务器内部错误（未预期的异常，兜底错误码） */
    INTERNAL_ERROR(500, "服务器内部错误"),

    // ==================== 用户模块（1001-1999） ====================

    /** 根据 ID 查询用户时，数据库中不存在该用户 */
    USER_NOT_FOUND(1001, "用户不存在"),

    /** 登录时用户名或密码不匹配（出于安全考虑，不区分是用户名错还是密码错） */
    USER_PASSWORD_ERROR(1002, "用户名或密码错误"),

    /** 注册时用户名已被占用 */
    USER_ALREADY_EXISTS(1003, "用户已存在"),

    /** 用户账号被管理员禁用，无法登录 */
    USER_ACCOUNT_DISABLED(1004, "账号已被禁用"),

    /** 修改密码时，输入的旧密码与数据库中的密文不匹配 */
    USER_OLD_PASSWORD_ERROR(1005, "旧密码不正确"),

    /** 修改密码时，两次输入的新密码不一致 */
    USER_PASSWORD_NOT_MATCH(1006, "两次输入的密码不一致"),

    /** 修改密码时，新密码与旧密码相同（无需修改） */
    USER_PASSWORD_SAME(1007, "新密码不能与旧密码相同"),

    // ==================== 商品模块（2001-2999） ====================

    /** 根据 ID 查询商品时，数据库中不存在该商品 */
    PRODUCT_NOT_FOUND(2001, "商品不存在"),

    /** 商品当前状态不允许执行该操作（如对已下架商品进行编辑） */
    PRODUCT_STATUS_ERROR(2002, "商品状态不合法"),

    // ==================== 分类模块（3001-3999） ====================

    /** 根据 ID 查询分类时，数据库中不存在该分类 */
    CATEGORY_NOT_FOUND(3001, "分类不存在"),

    /** 新增分类时，分类名称已被占用（分类名唯一约束） */
    CATEGORY_ALREADY_EXISTS(3002, "分类名称已存在"),

    // ==================== 订单模块（4001-4999） ====================

    /** 根据 ID 查询订单时，数据库中不存在该订单 */
    ORDER_NOT_FOUND(4001, "订单不存在"),

    /** 订单当前状态不允许执行该操作（如对已取消的订单进行确认） */
    ORDER_STATUS_ERROR(4002, "订单状态不合法"),

    /** 下单时商品已被他人购买（已售出）或已下架，不可再购买 */
    PRODUCT_NOT_AVAILABLE(4003, "商品已售出或已下架"),

    /** 买家和卖家是同一人，防止自买自卖 */
    CANNOT_BUY_OWN_PRODUCT(4004, "不能购买自己的商品"),

    // ==================== 收藏模块（5001-5999） ====================

    /** 重复收藏同一件商品（收藏关系唯一约束） */
    PRODUCT_ALREADY_FAVORITED(5001, "已经收藏过了"),

    /** 取消收藏时，该商品并未被当前用户收藏 */
    FAVORITE_NOT_FOUND(5002, "未收藏该商品"),

    // ==================== 留言模块（6001-6999） ====================
    COMMENT_NOT_FOUND(6001, "留言不存在"),
    CANNOT_DELETE_OTHERS_COMMENT(6002, "无权删除他人留言"),

    // ==================== 管理员模块（7001-7999） ====================

    /** 审核商品时，商品不在待审核状态（可能已被审核过或已下架） */
    PRODUCT_NOT_PENDING_REVIEW(7001, "商品不在待审核状态"),

    /** 封禁用户时，目标用户是管理员，不允许封禁 */
    CANNOT_BAN_ADMIN(7002, "不能封禁管理员");

    /**
     * 业务状态码
     * 前端根据此字段判断请求是否成功：code == 200 为成功，其他值为失败
     */
    private final Integer code;

    /**
     * 状态码对应的提示信息
     * 成功时为 "success"，失败时为具体的中文错误描述，可直接展示给用户
     */
    private final String message;

    /**
     * 枚举构造函数（Java 枚举的构造函数只能是 private 的，由编译器自动处理）
     * 每个枚举常量在类加载时调用此构造函数，初始化 code 和 message
     *
     * @param code    业务状态码
     * @param message 状态码对应的提示信息
     */
    ResultCode(Integer code, String message) {
        this.code = code;
        this.message = message;
    }
}
